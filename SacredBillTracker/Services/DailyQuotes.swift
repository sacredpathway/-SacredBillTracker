    /// Today's quote, cycled by day-of-year. Stable for a given calendar day.
    static func today(in calendar: Calendar = .current, now: Date = Date()) -> String {
        let day = calendar.ordinality(of: .day, in: .year, for: now) ?? 1
        let idx = (day - 1) % all.count
        return all[idx]
    }
